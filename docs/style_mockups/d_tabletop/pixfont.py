def text_width(text, font):
    return sum(len(font[c][0]) + 1 for c in text) - 1


def draw_text(img, x, y, text, font, color, outline=None, shadow=None, bold=False):
    """Draw text with optional 1px outline (all 8 directions) and/or drop shadow (dx,dy,color)."""
    px = img.load()
    W, H = img.size

    def put(cx, cy, col):
        if 0 <= cx < W and 0 <= cy < H:
            px[cx, cy] = col

    def glyph_pts():
        pts = []
        cx = x
        for c in text:
            g = font[c]
            for j, row in enumerate(g):
                for i, ch in enumerate(row):
                    if ch == "#":
                        pts.append((cx + i, y + j))
                        if bold:
                            pts.append((cx + i + 1, y + j))
            cx += len(g[0]) + 1 + (1 if bold else 0)
        return pts

    pts = glyph_pts()
    if shadow:
        dx, dy, sc = shadow
        for (a, b) in pts:
            put(a + dx, b + dy, sc)
    if outline:
        for (a, b) in pts:
            for dx in (-1, 0, 1):
                for dy in (-1, 0, 1):
                    put(a + dx, b + dy, outline)
    for (a, b) in pts:
        put(a, b, color)


def bold_width(text, font):
    return sum(len(font[c][0]) + 2 for c in text) - 1
